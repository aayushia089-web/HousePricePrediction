public class HouseData {

    double sqft;
    int bedrooms;
    int bathrooms;
    double price;

    public HouseData(double sqft,
                     int bedrooms,
                     int bathrooms,
                     double price) {

        this.sqft = sqft;
        this.bedrooms = bedrooms;
        this.bathrooms = bathrooms;
        this.price = price;
    }
}
